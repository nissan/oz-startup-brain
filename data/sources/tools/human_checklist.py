#!/usr/bin/env python3
"""Generates release/human-checklist.md: the blank human fact-check form for the federal pages (#62).

The form is derived from release/decisions.json (check IDs and questions) and the manifest (URL,
version ID, retrieval time and snapshot hash), so it cannot drift from the records it feeds. It never
carries results, names, dates or source text: every answer cell is blank. A person fills a copy;
an agent may transcribe that person's written record into decisions.json, and release_decisions.py
validates it there.

  python data/sources/tools/human_checklist.py --check   # exit 1 if the committed form is stale
  python data/sources/tools/human_checklist.py --write

Standard library only.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'release' / 'human-checklist.md'
EXPECTED_CHECKS = 15  # owner record item 5: the 15 priority checks on the four retrieved federal pages


def federal_pages(decisions, manifest):
    by_id = {s['source_id']: s for s in manifest['sources']}
    pages = []
    for d in decisions['sources']:
        m = by_id[d['source_id']]
        if d['retrieval']['state'] == 'reviewed_version' and 'AU-FED' in m['jurisdiction']:
            if m['source_version_id'] != d['retrieval']['source_version_id']:
                raise ValueError(f"{d['source_id']}: manifest and decisions disagree on the version")
            pages.append((d, m))
    count = sum(len(d['fact_checks']) for d, _ in pages)
    if count != EXPECTED_CHECKS:
        raise ValueError(f'expected {EXPECTED_CHECKS} federal checks, found {count}')
    return pages


def cell(text):
    return text.replace('|', '\\|')


def render(decisions, manifest):
    pages = federal_pages(decisions, manifest)
    lines = [
        '# Human fact-check form: federal pages (#62)',
        '',
        '<!-- Generated by data/sources/tools/human_checklist.py from decisions.json and the manifest. Do not edit by hand; regenerate with --write. -->',
        '',
        f'A blank form for the {EXPECTED_CHECKS} priority checks on the four retrieved federal pages. It is preparation only. Nothing here is a result, a decision or a release gate.',
        '',
        '## How to use it',
        '',
        '- **Who:** the person Nissan names on #28 or #62. Agents prepare and transcribe; they do not answer.',
        '- **Where to answer:** a copy of this form, an issue comment, or your own notes. Keep your own written record and link it from the transcription PR.',
        '- **What to check against:**',
        '  - `live_page`: the URL as it is on the day you check;',
        '  - the version ID: the private snapshot whose SHA-256 is listed. Ask whoever holds the snapshots for it.',
        '',
        '  Status and date checks age quickly, so check them close to release.',
        '- **Results**, one per check:',
        '  - `confirmed`: the page states it;',
        '  - `differs`: the page says something else;',
        '  - `not_stated`: the page does not say;',
        '  - `unclear`: the wording is ambiguous.',
        '',
        '  A `differs` result opens a follow-up and blocks that page.',
        '- **Notes:** in your own words, briefly. Do not paste source text into the repository.',
        '- **Fill in all four columns** for each check: result, your name, the date (YYYY-MM-DD) and what you checked against. The validator rejects agent names and missing dates.',
        '',
    ]
    for n, (d, m) in enumerate(pages, 1):
        lines += [
            f"## {n}. {d['title_as_cited']} (`{d['source_id']}`)",
            '',
            f"- Live page: <{d['url']}>",
            f"- Retrieved version: `{m['source_version_id']}`, fetched {m['fetched_at']}",
            f"- Snapshot SHA-256: `{m['content_hash']}`",
            f"- Retrieval evidence: [`{d['retrieval']['evidence']}`](../{d['retrieval']['evidence']})",
            '',
            '| Check | What to check | Result | Checked by | Checked on | Checked against | Note |',
            '| --- | --- | --- | --- | --- | --- | --- |',
        ]
        lines += [f"| `{c['check_id']}` | {cell(c['check'])} |  |  |  |  |  |" for c in d['fact_checks']]
        lines.append('')
    return '\n'.join(lines)


def main(argv):
    if argv not in (['--check'], ['--write']):
        print(__doc__.split('\n\n')[2], file=sys.stderr)
        return 2
    decisions = json.loads((ROOT / 'release' / 'decisions.json').read_text())
    manifest = json.loads((ROOT / 'article-bibliography.json').read_text())
    text = render(decisions, manifest)
    if argv == ['--write']:
        OUT.write_text(text)
        print(f'wrote {OUT.relative_to(ROOT.parent.parent)}')
        return 0
    if not OUT.exists() or OUT.read_text() != text:
        print(f'FAIL: {OUT.relative_to(ROOT.parent.parent)} is stale; run with --write', file=sys.stderr)
        return 1
    print(f'PASS: human checklist matches decisions.json and the manifest ({EXPECTED_CHECKS} blank checks)')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
