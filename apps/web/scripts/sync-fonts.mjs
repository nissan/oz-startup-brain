#!/usr/bin/env node
// Copies the pinned Fontsource WOFF2 files into public/fonts (gitignored) and writes
// src/styles/fonts.css from the packages' own @font-face rules, the same selection and the same
// family alias as design/tools/fonts.py: Fraunces (full variable), Atkinson Hyperlegible 400/700/
// 400 italic, JetBrains Mono 400; font-display: block; no font synthesis. Licences: SIL OFL 1.1,
// notices in design/tools/licenses/.
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const app = join(here, '..');
const require = createRequire(import.meta.url);
const SOURCES = {
  '@fontsource-variable/fraunces': ['full.css'],
  '@fontsource/atkinson-hyperlegible': ['400.css', '700.css', '400-italic.css'],
  '@fontsource/jetbrains-mono': ['400.css'],
};
const pins = JSON.parse(readFileSync(join(app, 'package.json'), 'utf8')).dependencies;
const outDir = join(app, 'public', 'fonts');
mkdirSync(outDir, { recursive: true });
mkdirSync(join(app, 'src', 'styles'), { recursive: true });

let css = '/* GENERATED by scripts/sync-fonts.mjs from the pinned Fontsource packages; do not edit. */\n';
let copied = 0;
for (const [pkg, files] of Object.entries(SOURCES)) {
  const pkgRoot = dirname(require.resolve(`${pkg}/package.json`));
  const actual = JSON.parse(readFileSync(join(pkgRoot, 'package.json'), 'utf8')).version;
  if (actual !== pins[pkg]) throw new Error(`FONT ${pkg}: expected ${pins[pkg]}, got ${actual}; run npm ci`);
  for (const file of files) {
    let sheet = readFileSync(join(pkgRoot, file), 'utf8');
    sheet = sheet.replace(/src:[^;]+;/g, (src) => {
      const m = /url\(([^)]+\.woff2)\)/.exec(src);
      if (!m) throw new Error(`FONT ${pkg}/${file}: no WOFF2 source`);
      const rel = m[1].replace(/["']/g, '');
      const from = join(pkgRoot, rel);
      if (!existsSync(from)) throw new Error(`FONT missing required face: ${from}`);
      copyFileSync(from, join(outDir, basename(rel)));
      copied += 1;
      return `src: url(/fonts/${basename(rel)}) format("woff2");`;
    });
    css += sheet.replace(/Fraunces Variable/g, 'Fraunces').replace(/font-display: swap/g, 'font-display: block');
  }
}
css += '\nhtml { font-synthesis: none; }\n';
writeFileSync(join(app, 'src', 'styles', 'fonts.css'), css);
console.log(`synced ${copied} font files into public/fonts`);
