#!/usr/bin/env node
// Wraps the committed design system (design/system/) as modules for apps/web, without editing it.
// The bundle is a classic IIFE that reads window.React and assigns window.OzStartupBrain; the
// wrapper gives it a private `window` object and re-exports the result, so the UI consumes the
// exact committed components (one source for the evidence-state words, #10) and server rendering
// works. Output is checked in under src/design-system/generated/ and drift-checked by
// `npm run check:generated` at the repository root.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', '..');
const system = join(root, 'design', 'system');
const out = join(here, '..', 'src', 'design-system', 'generated');
mkdirSync(out, { recursive: true });

const handoff = readFileSync(join(system, 'HANDOFF.md'), 'utf8');
const version = /Artifact version exported \| `([^`]+)`/.exec(handoff)?.[1] ?? 'unknown';
const bundle = readFileSync(join(system, 'components', 'bundle.js'), 'utf8');
const header = /^\/\* @ds-bundle: (\{.*\}) \*\//.exec(bundle);
if (!header) throw new Error('design/system/components/bundle.js has no @ds-bundle header');
const names = JSON.parse(header[1]).components.map((c) => c.name);

const banner = `// GENERATED by apps/web/scripts/sync-design-system.mjs from design/system (artifact version ${version}). Do not edit; edit design/system and run \`npm run generate\`.\n`;

writeFileSync(
  join(out, 'bundle.js'),
  `${banner}/* eslint-disable */\nimport * as React from 'react';\nconst window = { React };\n${bundle}\nconst OzStartupBrain = window.OzStartupBrain;\nexport default OzStartupBrain;\nexport const { ${names.join(', ')} } = OzStartupBrain;\nexport const DESIGN_SYSTEM_VERSION = ${JSON.stringify(version)};\n`,
);

const types = readFileSync(join(system, 'components', 'index.d.ts'), 'utf8');
writeFileSync(
  join(out, 'bundle.d.ts'),
  `${banner}import type * as React from 'react';\n${types}\n${names.map((n) => `export declare const ${n}: React.FC<${n}Props>;`).join('\n')}\nexport declare const DESIGN_SYSTEM_VERSION: string;\ndeclare const OzStartupBrain: { ${names.map((n) => `${n}: React.FC<${n}Props>`).join('; ')} };\nexport default OzStartupBrain;\n`,
);

for (const [src, dest] of [
  ['tokens.css', 'tokens.css'],
  ['components/bundle.css', 'bundle.css'],
]) {
  writeFileSync(join(out, dest), `/* GENERATED from design/system/${src} (artifact version ${version}); do not edit. */\n${readFileSync(join(system, src), 'utf8')}`);
}
console.log(`synced design system ${version}: ${names.length} components`);
